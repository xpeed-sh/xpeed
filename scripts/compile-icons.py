"""Compile the supplied filled SVG paths into theme-tinted vector meshes.
Supports absolute M/L/H/V/C/Z, no holes or transforms. No runtime SVG dependency.
Run after editing assets/icons/*.svg. Other SVG features need an extended importer.
"""
from pathlib import Path
import re
import xml.etree.ElementTree as ET


def cross(a, b, c):
    return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])


def polygon(data):
    tokens=re.findall(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?",data)
    points=[]; index=0; command=None
    while index < len(tokens):
        if tokens[index].isalpha():
            command=tokens[index];index+=1
        if command == 'Z':
            break
        count={'M':2,'L':2,'H':1,'V':1,'C':6}.get(command)
        if count is None:
            raise ValueError(f'Unsupported SVG command: {command}')
        values=list(map(float,tokens[index:index+count]));index+=count
        if command in ('M','L'):
            points.append(tuple(values)); command='L'
        elif command=='H':
            points.append((values[0],points[-1][1]))
        elif command=='V':
            points.append((points[-1][0],values[0]))
        else:
            a=points[-1];b=values[:2];c=values[2:4];d=values[4:]
            for step in range(1,13):
                t=step/12;u=1-t
                points.append(tuple(u**3*a[k]+3*u*u*t*b[k]+3*u*t*t*c[k]+t**3*d[k] for k in (0,1)))
    if sum((points[0][k]-points[-1][k])**2 for k in (0,1))<1e-12:
        points.pop()
    return points


def triangulate(points):
    order=list(range(len(points)))
    if sum(points[i][0]*points[(i+1)%len(points)][1]-points[(i+1)%len(points)][0]*points[i][1] for i in order)<0:
        order.reverse()
    triangles=[]
    while len(order)>3:
        for i,b in enumerate(order):
            a=order[i-1];c=order[(i+1)%len(order)]
            if cross(points[a],points[b],points[c])<=1e-10:
                continue
            if any(min(cross(points[a],points[b],points[p]),cross(points[b],points[c],points[p]),cross(points[c],points[a],points[p]))>=-1e-10 for p in order if p not in (a,b,c)):
                continue
            triangles.extend((a,b,c));order.pop(i);break
        else:
            raise ValueError('SVG polygon cannot be triangulated')
    return triangles+order


root=Path(__file__).resolve().parent.parent
out=['// Generated by scripts/compile-icons.py; edit assets/icons/*.svg.','pub type Layer = (f32, &\'static [[f32; 2]], &\'static [u32]);']
for name in ('settings','workspace','extensions','sidebar-left','sidebar-right','connection','moon','sun','file','folder','image','audio','video','minimize','maximize','close','home','info','copy','copy-checked','request-approval','full-access','access-selected','trash'):
    svg=ET.parse(root/f'assets/icons/{name}.svg')
    out.append(f'pub const {name.upper().replace("-", "_")}: &[Layer] = &[')
    for path in svg.iter('{http://www.w3.org/2000/svg}path'):
        if (name == 'audio' and len(re.findall(r'M[^M]*',path.attrib['d'])) == 3) or (name in ('info','copy-checked') and len(re.findall(r'M[^M]*',path.attrib['d'])) == 2):
            # This music note has one outline and two circular holes.
            import numpy as np
            import mapbox_earcut
            rings = [polygon(contour) for contour in re.findall(r'M[^M]*',path.attrib['d'])]
            points = [point for ring in rings for point in ring]
            indices = mapbox_earcut.triangulate_float64(np.array(points), np.cumsum([len(ring) for ring in rings], dtype=np.uint32)).tolist()
            vertices = ', '.join(f'[{x:.6f}, {y:.6f}]' for x,y in points)
            out.append(f'({float(path.attrib.get("opacity",1)):.1f}, &[{vertices}], &{indices}),')
            continue
        for contour in re.findall(r'M[^M]*',path.attrib['d']):
            points=polygon(contour); indices=triangulate(points)
            vertices=', '.join(f'[{x:.6f}, {y:.6f}]' for x,y in points)
            out.append(f'({float(path.attrib.get("opacity",1)):.1f}, &[{vertices}], &{indices}),')
    out.append('];')
from compile_logo import compile_logo
out.extend(compile_logo(root))
(root/'src/icon_meshes.rs').write_text('\n'.join(out)+'\n',encoding='utf-8')
